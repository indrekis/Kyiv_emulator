// ISA-06 D8-P3 — natural control progression through one full RAM write/read sweep.
// GY62 (1962), printed pp.170–171. ORIGINAL instructions; injected ROM + initial state.
// POLICY qualification, NOT a certified hardware trace. No CPU/ROM modifications.
