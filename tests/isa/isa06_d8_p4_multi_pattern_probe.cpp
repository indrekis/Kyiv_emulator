int main(int argc, char** argv) {
    try {
        std::string trace_path;
        if(argc==3 && std::string(argv[1])=="--trace") trace_path=argv[2];
        else if(argc!=1) {std::cerr<<"usage: test [--trace path.tsv]\n";return 2;}
        Trace trace(trace_path);
        bool a=two_cycles(trace);
        bool b=terminal_positive(trace);
        bool c=terminal_negative(trace);
        int passed=int(a)+int(b)+int(c);
        std::cout<<"ISA-06 D8-P4 STRICT=0/0 DOC-MISMATCH=0 POLICY="<<passed
                 <<"/3 POLICY-FAIL="<<(3-passed)<<" OBS=0\n";
        if(!trace_path.empty()) std::cout<<"TRACE="<<trace_path<<'\n';
        return passed==3?0:1;
    } catch (const std::exception& e) {
        std::cerr<<"POLICY-FAIL unhandled: "<<e.what()<<'\n';return 1;
    }
}
