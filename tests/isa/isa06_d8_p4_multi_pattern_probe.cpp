W historical(W pc) {
    for (auto e : HIST) if(e.pc == pc) return e.word;
    for (auto e : BRIDGE) if(e.pc == pc) return e.word;
    for (auto e : TAIL) if(e.pc == pc) return e.word;
    throw std::runtime_error("PC absent from transcribed historical window");
}
struct Silence {
    std::ostringstream out;
    std::streambuf* prev;
    Silence() : prev(std::cout.rdbuf(out.rdbuf())) {}
    ~Silence() { std::cout.rdbuf(prev); }
};
bool tick(Kyiv_t& cpu) { Silence s; return cpu.execute_opcode(); }
std::string oct(W w) {std::ostringstream s;s << std::oct << w;return s.str();}



struct Result {
    bool ok=true;
    std::string why;
    W bad_pc=0, bad_k=0;
    size_t steps=0, writes=0, reads=0;
    size_t neg_writes=0, neg_reads=0;
    bool handoff=false, reentry=false, finishing=false;
    W pattern_start=0, pattern_end=0;
    std::array<W,CELLS> snapshot{};
};
void fail(Result& r, W pc, W k, const std::string& reason) {
    r.ok=false; r.bad_pc=pc; r.bad_k=k; r.why=reason;
}
void initialize(Kyiv_t& cpu) {
    // All ROM/register/startup values are explicit test fixtures, not a ROM dump.
    cpu.kmem.write_rom(03012, 1);
    cpu.kmem.write_rom(03026, SIGN);
    cpu.kmem.write_rom(03042, TOP_MAG);
    for (auto e:HIST) cpu.kmem.write_memory(e.pc,e.word);
    for (auto e:BRIDGE) cpu.kmem.write_memory(e.pc,e.word);
    for (auto e:TAIL) cpu.kmem.write_memory(e.pc,e.word);
    cpu.kmem.write_memory(0014, 0);
    cpu.kmem.write_memory(0017, SENTINEL);
    cpu.kmem.write_memory(0021, SENTINEL);
    cpu.kmem.write_memory(0020, SENTINEL);
    for(W a=RAM_FIRST;a<=RAM_LAST;++a) cpu.kmem.write_memory(a,SENTINEL);
    cpu.C_reg=0120;cpu.A_reg=0;cpu.Loop_reg=077;cpu.P_reg=0371;cpu.T_reg=false;
}

struct Trace {
    std::ofstream out;
    explicit Trace(const std::string& path) {
        if(path.empty()) return;
        out.open(path,std::ios::binary|std::ios::trunc);
        if(!out) throw std::runtime_error("cannot open trace output: "+path);
        out << "scenario\tcycle\tstep\tpc\tk\ta_before\tcy_before\tpattern_before\tcell\tcode\tnext_pc\tstatus\n";
    }
    void log(const std::string& scenario, unsigned cycle, size_t step,
             W pc, W k, W a, W cy, W pat, W addr, W value,
             W next, const char* status) {
        if(!out) return;
        out << scenario << '\t' << cycle << '\t' << step << '\t'
            << oct(pc) << '\t' << oct(k) << '\t' << oct(a) << '\t'
            << oct(cy) << '\t' << oct(pat) << '\t'
            << oct(addr) << '\t' << oct(value) << '\t'
            << oct(next) << '\t' << status << '\n';
    }
};

Result sweep(Kyiv_t& cpu, unsigned cycle, Trace& trace) {
    Result r;
    bool saw_write_start=false, saw_read_start=false, saw_end_read=false;
    W first_pc=(cycle==1?0120:0121);
    if(cpu.C_reg!=first_pc) {
        fail(r,cpu.C_reg,0,"invalid cycle entry PC");return r;
    }
    for(size_t n=0;n<MAX_STEPS && r.ok;++n) {
        W pc=cpu.C_reg;
        if(pc==0121 && r.reentry) break; // next cycle is not executed by this invocation
        W expected_k=0;
        try {expected_k=historical(pc);}
        catch(const std::exception&) {fail(r,pc,0,"PC outside original transcription");break;}
        const W before_a=cpu.A_reg;
        const W before_cy=cpu.Loop_reg;
        const W before_pat=cpu.kmem.read_memory(0017);
        const W before_20=cpu.kmem.read_memory(0020);
        if(pc==0121 && r.pattern_start==0) r.pattern_start=before_pat;
        if(pc==0126 && (r.writes>=CELLS || before_a!=RAM_FIRST+r.writes)) {
            fail(r,pc,0,"nonsequential RAM write");break;
        }
        if(pc==0144) {
            if(r.reads>=CELLS || before_a!=RAM_FIRST+r.reads) {
                fail(r,pc,0,"nonsequential RAM read");break;
            }
            if(cpu.kmem.read_memory(before_a)!=r.snapshot[r.reads] ||
               cpu.kmem.read_memory(before_a)!=before_20) {
                fail(r,pc,0,"original comparison input differs from written 41-bit word");break;
            }
        }
        bool running=false;
        try {running=tick(cpu);}
        catch(const std::exception& e) {fail(r,pc,0,std::string("exception: ")+e.what());break;}
        ++r.steps;
        if(!running || cpu.T_reg || cpu.K_reg!=expected_k) {
            fail(r,pc,cpu.K_reg,"unexpected STOP or instruction K");break;
        }
        W cell_addr=0,cell_value=0;
        if(pc==0126) {
            cell_addr=before_a;
            cell_value=cpu.kmem.read_memory(before_a);
            if(cell_value!=before_20) {fail(r,pc,cpu.K_reg,"write did not preserve full code");break;}
            r.snapshot[r.writes++]=cell_value;
            if(cell_value==SIGN) ++r.neg_writes;
        }
        if(pc==0144) {
            cell_addr=before_a;
            cell_value=cpu.kmem.read_memory(before_a);
            if(cpu.C_reg!=0146) {fail(r,pc,cpu.K_reg,"original exact compare rejected code");break;}
            if(cell_value==SIGN) ++r.neg_reads;
            ++r.reads;
        }
        if(pc==0122) saw_write_start=true;
        if(pc==0137) {
            r.handoff=true;
            if(cpu.C_reg!=0140 || r.writes!=CELLS) {
                fail(r,pc,cpu.K_reg,"natural write-read handoff failed");break;
            }
        }
        if(pc==0140) saw_read_start=true;
        if(pc==0156) {
            saw_end_read=true;
            if(r.reads!=CELLS) {fail(r,pc,cpu.K_reg,"premature read end");break;}
        }
        if(pc==0160) {
            r.reentry=true;
            if(cpu.C_reg!=0121) {fail(r,pc,cpu.K_reg,"policy 05 reentry failed");break;}
        }
        bool checkpoint=(pc==0120||pc==0121||pc==0122||pc==0137||pc==0140||
                         pc==0156||pc==0157||pc==0160||
                         (pc==0126 && (r.writes<=2 || r.writes%64==0 || r.writes==CELLS))||
                         (pc==0144 && (r.reads<=2 || r.reads%64==0 || r.reads==CELLS)));
        if(checkpoint || !r.ok) trace.log("full_sweep",cycle,r.steps,pc,cpu.K_reg,
                           before_a,before_cy,before_pat,cell_addr,cell_value,
                           cpu.C_reg,r.ok?"OK":"FAIL");
    }
    r.pattern_end=cpu.kmem.read_memory(0017);
    if(r.ok && (!saw_write_start || !saw_read_start || !saw_end_read ||
                !r.handoff || !r.reentry || r.writes!=CELLS ||
                r.reads!=CELLS || cpu.C_reg!=0121 ||
                r.neg_writes!=r.neg_reads)) {
        fail(r,cpu.C_reg,cpu.K_reg,"cycle gates/counts/budget mismatch");
    }
    return r;
}

void print_run(const char* label, const Result& r) {
    std::cout << (r.ok?"POLICY-PASS ":"POLICY-FAIL ") << label
              << " steps="<<r.steps<<" writes="<<r.writes<<" reads="<<r.reads
              << " negzero_writes="<<r.neg_writes<<" negzero_reads="<<r.neg_reads
              << " pattern_start="<<oct(r.pattern_start)<<" pattern_end="<<oct(r.pattern_end)
              << " handoff="<<r.handoff<<" reentry="<<r.reentry
              << " first_bad_pc="<<oct(r.bad_pc)<<" fetched_K="<<oct(r.bad_k)
              << " reason="<<r.why<<'\n';
}

bool two_cycles(Trace& trace) {
    Kyiv_t cpu;initialize(cpu);
    Result a=sweep(cpu,1,trace);
    print_run("pattern_one_full_sweep",a);
    if(!a.ok) return false;
    Result b=sweep(cpu,2,trace);
    print_run("pattern_two_full_sweep",b);
    if(!b.ok) return false;
    size_t changed=0;
    for(size_t i=0;i<CELLS;++i) {
        W now=cpu.kmem.read_memory(RAM_FIRST+i);
        if(now!=b.snapshot[i]) {
            std::cout<<"POLICY-FAIL second sweep post-state drift at="<<oct(RAM_FIRST+i)<<'\n';
            return false;
        }
        if(a.snapshot[i]!=b.snapshot[i]) ++changed;
    }
    // These values are consequences of fixture ROM[3012]=+1 and original 0156.
    bool ok=a.pattern_start==1 && a.pattern_end==2 &&
            b.pattern_start==2 && b.pattern_end==4 && changed>0 &&
            a.neg_writes>0 && b.neg_writes>0 &&
            cpu.C_reg==0121 && !cpu.T_reg;
    std::cout<<(ok?"POLICY-PASS ":"POLICY-FAIL ")
             <<"two_cycle_rewrite_without_harness"
             <<" changed_cells="<<changed<<" total_steps="<<a.steps+b.steps
             <<" C="<<oct(cpu.C_reg)<<" pattern="<<oct(cpu.kmem.read_memory(0017))
             <<" negzero_cycle1="<<a.neg_writes<<" negzero_cycle2="<<b.neg_writes
             <<'\n';
    return ok;
}

bool terminal_positive(Trace& trace) {
    Kyiv_t cpu;initialize(cpu);
    // Inject ONLY the terminal precondition, not a claim of 39 prior sweeps.
    cpu.kmem.write_memory(0017,TOP_MAG);
    cpu.C_reg=0157;
    const W path[]={0157,0161,0162,0163};
    const W next[]={0161,0162,0163,0120};
    for(size_t i=0;i<4;++i) {
        const W pc=cpu.C_reg, pat=cpu.kmem.read_memory(0017), sign=cpu.kmem.read_memory(0014);
        bool running=false;
        try {running=tick(cpu);}
        catch(const std::exception& e) {std::cout<<"POLICY-FAIL terminal_positive exception="<<e.what()<<'\n';return false;}
        if(pc!=path[i] || cpu.K_reg!=historical(pc) || !running || cpu.T_reg || cpu.C_reg!=next[i]) {
            std::cout<<"POLICY-FAIL terminal_positive first_bad_pc="<<oct(pc)
                     <<" fetched_K="<<oct(cpu.K_reg)<<" C="<<oct(cpu.C_reg)<<'\n';return false;
        }
        trace.log("terminal_positive",0,i+1,pc,cpu.K_reg,cpu.A_reg,cpu.Loop_reg,pat,
                  0014,sign,cpu.C_reg,"OK");
    }
    bool ok=cpu.kmem.read_memory(0014)==SIGN && cpu.C_reg==0120;
    std::cout<<(ok?"POLICY-PASS ":"POLICY-FAIL ")
             <<"terminal_positive_0157_0163"
             <<" steps=4 0014="<<oct(cpu.kmem.read_memory(0014))
             <<" C="<<oct(cpu.C_reg)<<'\n';
    return ok;
}

bool terminal_negative(Trace& trace) {
    Kyiv_t cpu;initialize(cpu);
    cpu.kmem.write_memory(0014,SIGN);
    cpu.kmem.write_memory(0017,TOP_MAG);
    cpu.C_reg=0157;
    const W path[]={0157,0161};
    const W next[]={0161,0164};
    for(size_t i=0;i<2;++i) {
        W pc=cpu.C_reg,pat=cpu.kmem.read_memory(0017);
        bool running=false;
        try {running=tick(cpu);}
        catch(const std::exception& e) {std::cout<<"POLICY-FAIL terminal_negative exception="<<e.what()<<'\n';return false;}
        if(pc!=path[i] || cpu.K_reg!=historical(pc) || !running || cpu.T_reg || cpu.C_reg!=next[i]) {
            std::cout<<"POLICY-FAIL terminal_negative first_bad_pc="<<oct(pc)
                     <<" fetched_K="<<oct(cpu.K_reg)<<" C="<<oct(cpu.C_reg)<<'\n';return false;
        }
        trace.log("terminal_negative",0,i+1,pc,cpu.K_reg,cpu.A_reg,cpu.Loop_reg,pat,
                  0014,cpu.kmem.read_memory(0014),cpu.C_reg,"OK");
    }
    std::cout<<"POLICY-PASS terminal_negative_0157_0161 steps=2 C="<<oct(cpu.C_reg)
             <<" boundary=0164_UNEXECUTED\n";
    return true;
}
