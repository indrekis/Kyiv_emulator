using W = uint64_t;
constexpr W SIGN = W{1} << 40;
constexpr W TOP_MAG = W{1} << 39;
constexpr W RAM_FIRST = 0200;
constexpr W RAM_LAST = 01777;
constexpr size_t CELLS = RAM_LAST - RAM_FIRST + 1;
constexpr size_t MAX_STEPS = 25000;
constexpr W SENTINEL = 077;

struct HistoricalWord { W pc, word; };
